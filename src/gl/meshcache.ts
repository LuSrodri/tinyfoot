// Procedural models are generated once and then kept in the browser (IndexedDB), so a return
// visit does not rebuild them. Bump VERSION whenever a generator changes shape.

import type { MeshDef } from './meshes';

const VERSION = 'v3';
const DB = 'tinyfoot-meshes';
const STORE = 'meshes';

interface Stored {
  data: Float32Array;
  length: number;
  translucent?: boolean;
}

const memory = new Map<string, Stored>();
let db: IDBDatabase | null = null;

/** Loads every cached mesh into memory. Safe to await at start-up; it never rejects. */
export function loadMeshCache(): Promise<void> {
  return new Promise((resolve) => {
    try {
      const open = indexedDB.open(DB, 1);
      open.onupgradeneeded = () => open.result.createObjectStore(STORE);
      open.onerror = () => resolve();
      open.onsuccess = () => {
        db = open.result;
        const cursor = db.transaction(STORE).objectStore(STORE).openCursor();
        cursor.onerror = () => resolve();
        cursor.onsuccess = () => {
          const c = cursor.result;
          if (!c) return resolve();
          const key = String(c.key);
          if (key.startsWith(`${VERSION}:`)) memory.set(key, c.value as Stored);
          else c.delete(); // generated by an older version
          c.continue();
        };
      };
    } catch {
      resolve();
    }
    // Never hold up the app for a slow or blocked database.
    setTimeout(resolve, 1500);
  });
}

/** Returns the cached mesh for `key`, or builds it and stores it for next time. */
export function cachedMesh(key: string, build: () => MeshDef): MeshDef {
  const id = `${VERSION}:${key}`;
  const hit = memory.get(id);
  if (hit) return { data: hit.data, vertexCount: hit.data.length / 7, length: hit.length, translucent: hit.translucent };
  const mesh = build();
  const stored: Stored = { data: mesh.data, length: mesh.length, translucent: mesh.translucent };
  memory.set(id, stored);
  try {
    db?.transaction(STORE, 'readwrite').objectStore(STORE).put(stored, id);
  } catch {
    /* storage full or unavailable: the mesh simply is not kept */
  }
  return mesh;
}
